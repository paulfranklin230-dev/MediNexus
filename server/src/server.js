import dotenv from 'dotenv';
dotenv.config();
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import mongoose from 'mongoose';
import authRoutes from './routes/auth.js';
import patientRoutes from './routes/patients.js';
import recordRoutes from './routes/records.js';
import appointmentRoutes from './routes/appointments.js';
import miscRoutes from './routes/misc.js';
const app=express();
app.use(helmet()); app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173'}));
app.use(express.json({limit:'1mb'})); app.use(morgan('dev'));
app.use('/api',rateLimit({windowMs:15*60*1000,max:300}));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'MediNexus API'}));
app.use('/api/auth',authRoutes); app.use('/api/patients',patientRoutes);
app.use('/api/records',recordRoutes); app.use('/api/appointments',appointmentRoutes); app.use('/api',miscRoutes);
app.use((err,req,res,next)=>{console.error(err);res.status(err.status||500).json({message:err.message||'Server error'});});
const port=process.env.PORT||5000;
if(!process.env.MONGO_URI) console.error('MONGO_URI is missing. Add it to server/.env');
mongoose.connect(process.env.MONGO_URI).then(()=>{console.log('MongoDB connected');app.listen(port,()=>console.log(`MediNexus API running on ${port}`));}).catch(err=>{console.error('MongoDB connection failed:',err.message);process.exit(1);});
